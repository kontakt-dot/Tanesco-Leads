CREATE TABLE `mailSettings` (
	`id` int AUTO_INCREMENT NOT NULL,
	`tenantId` int NOT NULL,
	`provider` varchar(32) NOT NULL DEFAULT 'smtp',
	`host` varchar(200),
	`port` int DEFAULT 587,
	`secure` boolean NOT NULL DEFAULT false,
	`username` varchar(320),
	`password` text,
	`fromName` varchar(120),
	`fromEmail` varchar(320),
	`replyTo` varchar(320),
	`dailyLimit` int NOT NULL DEFAULT 300,
	`enabled` boolean NOT NULL DEFAULT false,
	`imapEnabled` boolean NOT NULL DEFAULT false,
	`imapHost` varchar(200),
	`imapPort` int DEFAULT 993,
	`imapUsername` varchar(320),
	`imapPassword` text,
	`lastTestAt` timestamp,
	`lastTestStatus` varchar(40),
	`lastError` text,
	`lastReplyCheckAt` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `mailSettings_id` PRIMARY KEY(`id`),
	CONSTRAINT `mail_settings_tenant_unique` UNIQUE(`tenantId`)
);
